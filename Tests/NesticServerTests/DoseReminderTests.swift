@testable import NesticServer
import Testing
import VaporTesting
import Fluent

@Suite("Medication course reminders", .serialized, .enabled(if: Environment.get("RUN_DATABASE_TESTS") == "true"))
struct DoseReminderTests {
    private func withApp(_ test: (Application) async throws -> Void) async throws {
        let app = try await Application.make(.testing)
        do {
            try await configure(app)
            try await test(app)
            try await app.asyncShutdown()
        } catch {
            try await app.asyncShutdown()
            throw error
        }
    }
    @Test("Dose resets, course totals, corrections, account sync, and private isolation")
    func course() async throws {
        try await withApp { app in
            try await app.autoMigrate()
            let suffix = UUID().uuidString
            let user = User(email: "dose-\(suffix)@example.com", passwordHash: "unused", displayName: "Dose owner", emailVerified: true)
            let other = User(email: "dose-other-\(suffix)@example.com", passwordHash: "unused", displayName: "Other", emailVerified: true)
            try await user.save(on: app.db); try await other.save(on: app.db)
            let nest = Nest(name: "Dose tests"); try await nest.save(on: app.db)
            let nestID = try nest.requireID(), userID = try user.requireID()
            try await NestMember(nestID: nestID, userID: userID, role: .owner).save(on: app.db)
            try await NestMember(nestID: nestID, userID: try other.requireID(), role: .admin).save(on: app.db)
            let subject = Entity(nestID: nestID, kind: .person, name: "Person"); try await subject.save(on: app.db)
            let subjectID = try subject.requireID()
            let tracker = TrackableAction(nestID: nestID, name: "Pills", valueType: .number)
            tracker.privateOwnerId = userID; try await tracker.save(on: app.db)
            let trackerID = try tracker.requireID()
            let token = try await app.jwt.keys.sign(SessionToken(userId: userID))
            let headers: HTTPHeaders = ["Authorization": "Bearer \(token)"]
            let api = try app.testing()
            let start = Date().addingTimeInterval(-48 * 3600)
            let input = NestReminderRequest(subjectID: subjectID, trackerID: trackerID, intervalHours: 8, totalPills: 3, cadence: .afterDose, linkedTrackerID: nil, delayMinutes: 0, anchorDate: start, hour: 0, minute: 0)
            let created = try await api.sendRequest(.POST, "nests/\(nestID)/reminders", headers: headers, beforeRequest: { req async throws in try req.content.encode(input) })
            #expect(created.status == .ok)
            let r = try created.content.decode(NestReminderResponse.self)
            #expect(r.lastDoseAt == nil); #expect(r.pillsTaken == 0)
            let older = ActionEvent(nestID: nestID, entityID: subjectID, actionID: trackerID, actorUserID: userID, occurredAt: start.addingTimeInterval(-1), valueNumber: 20)
            try await older.save(on: app.db)
            let first = ActionEvent(nestID: nestID, entityID: subjectID, actionID: trackerID, actorUserID: userID, occurredAt: start.addingTimeInterval(3600), valueNumber: 1)
            try await first.save(on: app.db)
            let second = ActionEvent(nestID: nestID, entityID: subjectID, actionID: trackerID, actorUserID: userID, occurredAt: start.addingTimeInterval(30 * 3600), valueNumber: 2)
            try await second.save(on: app.db)
            let read = try await api.sendRequest(.GET, "nests/\(nestID)/reminders", headers: headers)
            let finished = try #require(read.content.decode([NestReminderResponse].self).first)
            #expect(finished.intervalHours == 8); #expect(finished.totalPills == 3)
            #expect(finished.pillsTaken == 3)
            #expect(abs(try #require(finished.lastDoseAt).timeIntervalSince(second.occurredAt)) < 1)
            try await second.delete(on: app.db)
            let corrected = try await api.sendRequest(.GET, "nests/\(nestID)/reminders", headers: headers)
            let active = try #require(corrected.content.decode([NestReminderResponse].self).first)
            #expect(active.pillsTaken == 1)
            #expect(abs(try #require(active.lastDoseAt).timeIntervalSince(first.occurredAt)) < 1)
            let otherToken = try await app.jwt.keys.sign(SessionToken(userId: try other.requireID()))
            let hidden = try await api.sendRequest(.GET, "nests/\(nestID)/reminders", headers: ["Authorization": "Bearer \(otherToken)"])
            #expect(try hidden.content.decode([NestReminderResponse].self).isEmpty)
            let invalid = NestReminderRequest(subjectID: subjectID, trackerID: trackerID, intervalHours: 0, totalPills: 0, cadence: .afterDose, linkedTrackerID: nil, delayMinutes: 0, anchorDate: start, hour: 0, minute: 0)
            let bad = try await api.sendRequest(.POST, "nests/\(nestID)/reminders", headers: headers, beforeRequest: { req async throws in try req.content.encode(invalid) })
            #expect(bad.status == .badRequest)
            tracker.valueType = .text; try await tracker.save(on: app.db)
            let ongoing = NestReminderRequest(subjectID: subjectID, trackerID: trackerID, intervalHours: 1.0 / 60.0, totalPills: nil, cadence: .afterDose, linkedTrackerID: nil, delayMinutes: 0, anchorDate: start, hour: 0, minute: 0)
            let generic = try await api.sendRequest(.POST, "nests/\(nestID)/reminders", headers: headers, beforeRequest: { req async throws in try req.content.encode(ongoing) })
            #expect(generic.status == .ok)
            #expect(try generic.content.decode(NestReminderResponse.self).intervalHours == 1.0 / 60.0)
            let genericID = try generic.content.decode(NestReminderResponse.self).id
            let update = ActionEvent(nestID: nestID, entityID: subjectID, actionID: trackerID, actorUserID: userID, occurredAt: Date().addingTimeInterval(-60), valueNumber: 0, valueText: "Watered", valueBool: false)
            try await update.save(on: app.db)
            let refreshed = try await api.sendRequest(.GET, "nests/\(nestID)/reminders", headers: headers)
            let interval = try #require(refreshed.content.decode([NestReminderResponse].self).first { $0.id == genericID })
            #expect(abs(try #require(interval.lastDoseAt).timeIntervalSince(update.occurredAt)) < 1)
            tracker.allowedMemberIDs = [try other.requireID()]; try await tracker.save(on: app.db)
            let choice = UpdateReminderNotificationRequest(enabled: true, deliveryMode: "both")
            let selected = try await api.sendRequest(.PUT, "nests/\(nestID)/reminders/\(genericID)/notification", headers: headers, beforeRequest: { req async throws in try req.content.encode(choice) })
            #expect(selected.status == .ok)
            #expect(try selected.content.decode(NestReminderResponse.self).deliveryMode == "both")
            let otherRead = try await api.sendRequest(.GET, "nests/\(nestID)/reminders", headers: ["Authorization": "Bearer \(otherToken)"])
            #expect(try otherRead.content.decode([NestReminderResponse].self).first { $0.id == genericID }?.deliveryMode == "notification")
            let off = UpdateReminderNotificationRequest(enabled: false, deliveryMode: nil)
            let disabled = try await api.sendRequest(.PUT, "nests/\(nestID)/reminders/\(genericID)/notification", headers: headers, beforeRequest: { req async throws in try req.content.encode(off) })
            let disabledReminder = try disabled.content.decode(NestReminderResponse.self)
            #expect(disabledReminder.deliveryMode == "both"); #expect(!disabledReminder.notificationsEnabled)
            let invalidMode = UpdateReminderNotificationRequest(enabled: true, deliveryMode: "invalid")
            let rejected = try await api.sendRequest(.PUT, "nests/\(nestID)/reminders/\(genericID)/notification", headers: headers, beforeRequest: { req async throws in try req.content.encode(invalidMode) })
            #expect(rejected.status == .badRequest)
            try await EntityPinnedAction(entityID: subjectID, actionID: trackerID, sortOrder: 0).save(on: app.db)
            first.photoURL = "r2://archive-test/photo.jpg"; try await first.save(on: app.db)
            let archived = try await api.sendRequest(.DELETE, "actions/\(trackerID)", headers: headers)
            #expect(archived.status == .noContent)
            #expect(try await TrackableAction.find(trackerID, on: app.db)?.isArchived == true)
            #expect(try await ActionEvent.find(first.requireID(), on: app.db)?.photoURL == "r2://archive-test/photo.jpg")
            #expect(try await ActionEvent.query(on: app.db).filter(\.$action.$id == trackerID).count() == 3)
            #expect(try await NestReminder.query(on: app.db).filter(\.$trackerID == trackerID).count() == 0)
            #expect(try await EntityPinnedAction.query(on: app.db).filter(\.$action.$id == trackerID).count() == 0)
            let invalidReminder = try await api.sendRequest(.POST, "nests/\(nestID)/reminders", headers: headers, beforeRequest: { req async throws in try req.content.encode(ongoing) })
            #expect(invalidReminder.status == .badRequest)
            struct LogArchived: Content { let actionID: UUID; let valueText: String }
            let logArchived = try await api.sendRequest(.POST, "entities/\(subjectID)/events", headers: headers, beforeRequest: { req async throws in try req.content.encode(LogArchived(actionID: trackerID, valueText: "Should not save")) })
            #expect(logArchived.status == .badRequest)
            let replacement = TrackableAction(nestID: nestID, name: tracker.name, valueType: .text)
            replacement.privateOwnerId = userID; try await replacement.save(on: app.db)
            #expect(try replacement.requireID() != trackerID)
            tracker.allowedMemberIDs = []; tracker.isArchived = true; try await tracker.save(on: app.db)
            let hiddenArchive = try await api.sendRequest(.GET, "nests/\(nestID)/events", headers: ["Authorization": "Bearer \(otherToken)"])
            #expect(try hiddenArchive.content.decode([ActionEventResponse].self).isEmpty)
            try await nest.delete(on: app.db); try await user.delete(on: app.db); try await other.delete(on: app.db)
        }
    }
    @Test("Routine reminders reset only after a full routine log and stay private")
    func routineReminders() async throws {
        try await withApp { app in
            try await app.autoMigrate()
            let suffix = UUID().uuidString
            let owner = User(email: "routine-reminder-\(suffix)@example.com", passwordHash: "unused", displayName: "Owner", emailVerified: true)
            let other = User(email: "routine-other-\(suffix)@example.com", passwordHash: "unused", displayName: "Other", emailVerified: true)
            try await owner.save(on: app.db); try await other.save(on: app.db)
            let nest = Nest(name: "Routine reminders"); try await nest.save(on: app.db)
            let nestID = try nest.requireID(), userID = try owner.requireID()
            try await NestMember(nestID: nestID, userID: userID, role: .owner).save(on: app.db)
            try await NestMember(nestID: nestID, userID: other.requireID(), role: .admin).save(on: app.db)
            let subject = Entity(nestID: nestID, kind: .person, name: "Me"); try await subject.save(on: app.db)
            let tracker = TrackableAction(nestID: nestID, name: "Private update", valueType: .none)
            tracker.privateOwnerId = userID; try await tracker.save(on: app.db)
            let subjectID = try subject.requireID(), trackerID = try tracker.requireID()
            try await EntityPinnedAction(entityID: subjectID, actionID: trackerID, sortOrder: 0).save(on: app.db)
            let routine = Routine(nestID: nestID, name: "Private routine", targets: [RoutineTarget(entityID: subjectID, items: [RoutineItem(trackerID: trackerID, valueNumber: nil, valueText: nil, valueBool: nil, valueJSON: nil)])])
            routine.privateOwnerId = userID; try await routine.save(on: app.db)
            let routineID = try routine.requireID()
            let headers: HTTPHeaders = ["Authorization": "Bearer \(try await app.jwt.keys.sign(SessionToken(userId: userID)))"]
            let otherHeaders: HTTPHeaders = ["Authorization": "Bearer \(try await app.jwt.keys.sign(SessionToken(userId: other.requireID())))"]
            let api = try app.testing(), start = Date().addingTimeInterval(-7200)
            let input = NestReminderRequest(routineID: routineID, startFromFirstTracking: true, subjectID: subjectID, trackerID: routineID, intervalHours: 8, totalPills: nil, cadence: .afterDose, linkedTrackerID: nil, delayMinutes: 0, anchorDate: start, hour: 9, minute: 0)
            let created = try await api.sendRequest(.POST, "nests/\(nestID)/reminders", headers: headers, beforeRequest: { req async throws in try req.content.encode(input) })
            #expect(created.status == .ok)
            let reminder = try created.content.decode(NestReminderResponse.self)
            #expect(reminder.routineID == routineID); #expect(reminder.lastDoseAt == nil)
            try await ActionEvent(nestID: nestID, entityID: subjectID, actionID: trackerID, actorUserID: userID, occurredAt: Date()).save(on: app.db)
            let unchanged = try await api.sendRequest(.GET, "nests/\(nestID)/reminders", headers: headers)
            #expect(try unchanged.content.decode([NestReminderResponse].self).first?.lastDoseAt == nil)
            struct Log: Content { let occurredAt: Date }
            let loggedAt = Date().addingTimeInterval(-3600)
            let logged = try await api.sendRequest(.POST, "routines/\(routineID)/log", headers: headers, beforeRequest: { req async throws in try req.content.encode(Log(occurredAt: loggedAt)) })
            #expect(logged.status == .ok)
            let routineEvents = try logged.content.decode([ActionEventResponse].self)
            #expect(!routineEvents.isEmpty && routineEvents.allSatisfy { abs($0.occurredAt.timeIntervalSince(loggedAt)) < 1 })
            let read = try await api.sendRequest(.GET, "nests/\(nestID)/reminders", headers: headers)
            let last = try read.content.decode([NestReminderResponse].self).first?.lastDoseAt
            #expect(last != nil && abs(last!.timeIntervalSince(loggedAt)) < 1)
            let hidden = try await api.sendRequest(.GET, "nests/\(nestID)/reminders", headers: otherHeaders)
            #expect(try hidden.content.decode([NestReminderResponse].self).isEmpty)
            let guessed = try await api.sendRequest(.PUT, "nests/\(nestID)/reminders/\(reminder.id)/notification", headers: otherHeaders, beforeRequest: { req async throws in try req.content.encode(UpdateReminderNotificationRequest(enabled: true, deliveryMode: "both")) })
            #expect(guessed.status == .notFound)
            let weekly = NestReminderRequest(routineID: routineID, recurrenceDays: 7, subjectID: subjectID, trackerID: routineID, intervalHours: nil, totalPills: nil, cadence: .everyOtherDay, linkedTrackerID: nil, delayMinutes: 0, anchorDate: start, hour: 9, minute: 0)
            let weeklyCreated = try await api.sendRequest(.POST, "nests/\(nestID)/reminders", headers: headers, beforeRequest: { req async throws in try req.content.encode(weekly) })
            #expect(weeklyCreated.status == .ok)
            #expect(try weeklyCreated.content.decode(NestReminderResponse.self).recurrenceDays == 7)
            let deleted = try await api.sendRequest(.DELETE, "routines/\(routineID)", headers: headers)
            #expect(deleted.status == .noContent)
            #expect(try await NestReminder.query(on: app.db).filter(\.$routineID == routineID).count() == 0)
            try await nest.delete(on: app.db); try await owner.delete(on: app.db); try await other.delete(on: app.db)
        }
    }

}
